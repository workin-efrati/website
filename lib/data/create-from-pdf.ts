import { Article, generateId, Section } from "./create";

export function parseArticleText(rawText: string): Article {
   const lines = rawText
      .split('\n')
      .map(l => l.trim())
      .filter(Boolean);

   const article: Article = {
      id: generateId(),
      slug: "pesach-article",
      title: lines[0] || "מאמר",
      author: "לא ידוע",
      publishedAt: new Date().toISOString(),
      sections: []
   };

   let currentSection: Section = {
      id: generateId(),
      title: "תוכן",
      blocks: []
   };

   article.sections.push(currentSection);

   let buffer: string[] = [];

   function flushParagraph() {
      if (!buffer.length) return;

      const text = buffer.join(' ')
         .replace(/\s+/g, ' ')
         .trim();

      currentSection.blocks.push({
         id: generateId(),
         type: "paragraph",
         text
      });

      buffer = [];
   }

   lines.forEach((line) => {
      // 🔹 Detect possible section titles
      const isLikelyTitle =
         line.length < 60 &&
         !line.endsWith('.') &&
         !line.includes('״') &&
         !line.includes(':');

      // 🔹 Detect page markers like "273"
      const isPageMarker = /^\d{2,4}/.test(line);

      if (isLikelyTitle || isPageMarker) {
         flushParagraph();

         currentSection = {
            id: generateId(),
            title: line,
            blocks: []
         };

         article.sections.push(currentSection);
         return;
      }

      // 🔹 Detect quotes (Rambam etc.)
      if (line.includes('״') || line.includes('"')) {
         flushParagraph();

         currentSection.blocks.push({
            id: generateId(),
            type: "heading",
            level: 3,
            text: line
         });

         return;
      }

      // 🔹 Otherwise accumulate paragraph
      buffer.push(line);
   });

   flushParagraph();

   return article;
}

